# ---------------------------------------------------------------------------
# Toric surfaces with an affine action of a finite group: class in BC_2(G).
#
# Setting. T = (k^*)^2 = N (x) k^* with N = Z^2. A finite group G acts on T by affine maps
#     x -> t * nu(x),     nu in GL_2(Z) acting on N (x) k^*,   t = exp(2 pi i t) a torsion point, t in (Q/Z)^2,
# and on a smooth complete toric surface X_Sigma for a fan Sigma invariant under all nu. This is the group of
# monomial maps: translations by finite subgroups of T extended by automorphisms of the lattice.
#
# Conventions (documented where chosen, each checked in the tests).
#  K1 The action is a LEFT action. The affine map (nu, t) is x -> t * nu(x). Composition is
#     (nu1, t1) o (nu2, t2) = (nu1 nu2, t1 + nu1 t2). `ToricAction` checks that g -> image(g) is a homomorphism for
#     the product of G read as composition (convention :left) or as the opposite composition (:right). This is the
#     hom versus anti-hom trap, so the whole Cayley graph of G is checked, not only the relations of generators.
#  K2 Weights are eigenvalues of the differential of the action on points. A translation by t acts on the
#     coordinate function chi^m by multiplication by exp(2 pi i <m, t>). A character beta of a group H with
#     independent generators h_j is given by integers c_j with beta(h_j) = exp(2 pi i c_j / ord(h_j)).
#  K3 Standard form. The boundary of X_Sigma is the divisor D of the rays. The action is in standard form with
#     respect to D plus exceptional divisors over the isolated fixed points of T provided that no two rays of one
#     G-orbit span a cone (`equivariant_refinement` achieves this by star subdivisions).
#  K4 Hypothesis of the first version, lifted in 2.6c for reflections by the code of `src/toric_reflections.jl`. Without reflections: no element of nu(G) other than the identity has an eigenvalue 1, that is
#     det(nu - 1) != 0. Then every element with nu != 1 has finitely many fixed points in T, no ray and no cone is fixed
#     by it, and the stabilizer in G of a point of the boundary is contained in A = G cap T (translations).
#     The fixed points of T have cyclic stabilizers and tangent weights (b, -b) (the eigenvalues of a finite order
#     element of GL_2(Z) without eigenvalue 1 are conjugate, or equal to -1 twice), so each of their point symbols vanishes
#     by (V), and the blowup of such a point gives, by (B), the same class. They contribute nothing to the class.
#     Actions with reflections have fixed curves, see `src/toric_reflections.jl` for their symbols.
#  K5 Strata of the boundary and their symbols (H, Y, beta), H the pointwise stabilizer, Y~ the stabilizer of the
#     stratum (preimage convention), beta the weights of H on the normal space:
#       ray rho:        H = {a in A : t_a in R rho},  Y~ = {g : nu_g rho = rho},  beta = tautological character of H.
#       cone (r1, r2):  H = A,  Y~ = A,  beta = (the coordinates of t_a in the basis (r1, r2)) for a in A.
#     Strata whose symbol has a trivial character, or trivial H, contribute nothing.
# ---------------------------------------------------------------------------

"""
    AffineTorusMap(nu, t)

An affine automorphism of the torus T = (k^*)^2 of the form `x -> t * nu(x)`.

`nu` is an integer 2 by 2 matrix of determinant plus or minus one acting on the cocharacter lattice and `t` is a
vector of two rationals, the torsion point `exp(2 pi i t)` of T, taken modulo 1. Composition is
`(nu1, t1) o (nu2, t2) = (nu1 nu2, t1 + nu1 t2)` and `f * g` is `f` after `g` for the convention `:left` of
`ToricAction`. Throws `ArgumentError` for a matrix that is not in GL_2(Z).

# Examples

```jldoctest
f = AffineTorusMap([0 -1; 1 -1], [1//8, 0])
println(f.nu, " ", f.t)

# output

[0 -1; 1 -1] Rational{Int64}[1//8, 0]
```
"""
struct AffineTorusMap
    nu::Matrix{Int}
    t::Vector{Rational{Int}}
    function AffineTorusMap(nu, t)
        size(nu) == (2, 2) || throw(ArgumentError("only dimension 2 is implemented: nu must be a 2 by 2 matrix"))
        length(t) == 2 || throw(ArgumentError("t must have two coordinates"))
        d = nu[1, 1] * nu[2, 2] - nu[1, 2] * nu[2, 1]
        abs(d) == 1 || throw(ArgumentError("nu must have determinant 1 or -1, it has determinant $d"))
        tt = Rational{Int}[_mod1(Rational{Int}(x)) for x in t]
        return new(Matrix{Int}(nu), tt)
    end
end

_mod1(x::Rational{Int}) = x - floor(Int, x)
_det2(m) = m[1, 1] * m[2, 2] - m[1, 2] * m[2, 1]
_id2() = [1 0; 0 1]

_compose(f::AffineTorusMap, g::AffineTorusMap) = AffineTorusMap(f.nu * g.nu, f.t .+ f.nu * g.t)
Base.:*(f::AffineTorusMap, g::AffineTorusMap) = _compose(f, g)
Base.:(==)(f::AffineTorusMap, g::AffineTorusMap) = f.nu == g.nu && f.t == g.t
Base.hash(f::AffineTorusMap, h::UInt) = hash((f.nu, f.t), h)
Base.show(io::IO, f::AffineTorusMap) = print(io, "AffineTorusMap(", f.nu, ", ", f.t, ")")

"""
    affine_group(maps) -> (G, gens)

The group generated by affine maps of the torus, as a permutation group.

`maps` is a vector of `AffineTorusMap`. Returns a permutation group `G` of the group generated by the maps
under composition, acting on itself by right multiplication, and the images of the maps as its generators. The
map from `G` to the affine maps sending `gens[i]` to `maps[i]` is a homomorphism for the convention `:left`.

# Examples

```jldoctest
c = AffineTorusMap([0 -1; 1 -1], [0, 0])
a = AffineTorusMap([1 0; 0 1], [1//3, 0])
G, gens = affine_group([a, c])
println(order(G))

# output

27
```
"""
function affine_group(maps::Vector{AffineTorusMap})
    G, gs, _ = _affine_data(maps)
    return G, gs
end

# The group generated by `maps`, the generators as elements of it, and the affine map of every element.
function _affine_data(maps::Vector{AffineTorusMap})
    isempty(maps) && throw(ArgumentError("give at least one generator"))
    ident = AffineTorusMap(_id2(), [0, 0])
    elems = AffineTorusMap[ident]
    index = Dict{AffineTorusMap,Int}(ident => 1)
    queue = [ident]
    while !isempty(queue)
        x = popfirst!(queue)
        for s in maps
            y = _compose(x, s)
            if !haskey(index, y)
                push!(elems, y); index[y] = length(elems); push!(queue, y)
            end
        end
    end
    N = length(elems)
    # g acts on the elements by right multiplication x -> x o g, so that the product of permutations
    # (first g, then h) is the composition g o h, and the image of g is the image of the identity
    Sym = symmetric_group(N)
    perms = [perm(Sym, [index[_compose(x, s)] for x in elems]) for s in maps]
    G, _ = sub(Sym, perms)
    images = Dict{Any,AffineTorusMap}()
    for g in G
        images[g] = elems[Int(g(1))]
    end
    return G, [G(p) for p in perms], images
end

"""
    ToricAction(G, maps, rays; convention = :left)
    ToricAction(maps, rays)

A finite group acting on a smooth complete toric surface by affine maps.

`G` is a finite OSCAR group, `maps` the images of `gens(G)` as `AffineTorusMap` and `rays` the primitive
generators of the one dimensional cones of the fan in counterclockwise order. The second form builds the group
from the maps with `affine_group`, and `act.gens` are then the elements of `act.G` that correspond to the maps, in
the given order, so that homomorphisms between two actions can be defined on generators. The constructor extends `maps` to all of `G` by walking the Cayley graph and
checks that this is well defined, which tests the homomorphism property for the whole group, and that the action
is faithful. `convention` is `:left` if the product `g * h` of `G` is the composition `g` after `h` and `:right`
if it is `h` after `g`. Throws `ArgumentError` if the map is not a homomorphism for the chosen convention, if it
is not faithful, or if the fan is not a smooth complete fan invariant under the linear parts.

# Examples

```jldoctest
a = AffineTorusMap([1 0; 0 1], [1//8, 0])
b = AffineTorusMap([1 0; 0 1], [0, 7//8])
c = AffineTorusMap([0 -1; 1 -1], [0, 0])
act = ToricAction([a, b, c], toric_fan_P2())
println(order(act.G))

# output

192
```
"""
struct ToricAction
    G::Any
    images::Dict{Any,AffineTorusMap}
    rays::Vector{Vector{Int}}
    gens::Vector{Any}      # the elements of G that correspond to the given affine maps, in the given order
end

"""
    toric_fan_P2()

The rays of the fan of the projective plane, `(1,0), (0,1), (-1,-1)`, in counterclockwise order.
"""
toric_fan_P2() = [[1, 0], [0, 1], [-1, -1]]

"""
    toric_fan_hexagon()

The rays `(1,0), (1,1), (0,1), (-1,0), (-1,-1), (0,-1)` of the fan of the del Pezzo surface of degree 6,
which is the projective plane blown up at its three fixed points, in counterclockwise order.
"""
toric_fan_hexagon() = [[1, 0], [1, 1], [0, 1], [-1, 0], [-1, -1], [0, -1]]

function _check_fan(rays)
    length(rays) >= 3 || throw(ArgumentError("a complete fan needs at least three rays"))
    for r in rays
        gcd(r[1], r[2]) == 1 || throw(ArgumentError("the ray $r is not primitive"))
    end
    total = 0.0
    for i in eachindex(rays)
        r, s = rays[i], rays[mod1(i + 1, length(rays))]
        d = r[1] * s[2] - r[2] * s[1]
        d == 1 || throw(ArgumentError("rays $r and $s do not span a smooth cone in counterclockwise order (determinant $d)"))
        total += atan(d, r[1] * s[1] + r[2] * s[2])
    end
    abs(total - 2pi) < 1e-9 || throw(ArgumentError("the rays do not go around the origin exactly once"))
    return nothing
end

function ToricAction(G, maps::Vector{AffineTorusMap}, rays::Vector{<:AbstractVector{<:Integer}}; convention::Symbol = :left)
    convention in (:left, :right) || throw(ArgumentError("convention must be :left or :right"))
    gs = gens(G)
    length(gs) == length(maps) || throw(ArgumentError("give one affine map for each of the $(length(gs)) generators of G"))
    rays2 = [Int.(collect(r)) for r in rays]
    _check_fan(rays2)
    comp(f, g) = convention == :left ? _compose(f, g) : _compose(g, f)
    ident = AffineTorusMap(_id2(), [0, 0])
    images = Dict{Any,AffineTorusMap}(one(G) => ident)
    queue = Any[one(G)]
    while !isempty(queue)
        x = popfirst!(queue)
        for (s, m) in zip(gs, maps)
            y = x * s
            want = comp(images[x], m)
            if haskey(images, y)
                images[y] == want || throw(ArgumentError(
                    "the map on generators does not extend to a homomorphism for convention :$convention " *
                    "(try the other convention if G acts on the right)"))
            else
                images[y] = want
                push!(queue, y)
            end
        end
    end
    length(Set(values(images))) == length(images) ||
        throw(ArgumentError("the action is not faithful: two elements of G give the same affine map"))
    nus = unique([f.nu for f in values(images)])
    rayset = Set(rays2)
    for nu in nus, r in rays2
        Int.(nu * r) in rayset || throw(ArgumentError("the fan is not invariant: the linear part $nu sends the ray $r to a vector that is not a ray"))
    end
    return ToricAction(G, images, rays2, Any[g for g in gs])
end

function ToricAction(maps::Vector{AffineTorusMap}, rays)
    G, gs, images = _affine_data(maps)
    rays2 = [Int.(collect(r)) for r in rays]
    _check_fan(rays2)
    rayset = Set(rays2)
    for nu in unique([f.nu for f in values(images)]), r in rays2
        Int.(nu * r) in rayset || throw(ArgumentError("the fan is not invariant: the linear part $nu sends the ray $r to a vector that is not a ray"))
    end
    return ToricAction(G, images, rays2, Any[g for g in gs])
end

# distinct linear parts of the group
_linear_parts(act::ToricAction) = unique([f.nu for f in values(act.images)])

# orbit of a ray under a list of matrices, as a set of rays
function _ray_orbit(r, nus)
    out = Set{Vector{Int}}(); push!(out, r)
    for nu in nus
        push!(out, Int.(nu * r))
    end
    return out
end

"""
    equivariant_refinement(act::ToricAction; property_E = true) -> Vector{Vector{Int}}

Rays of a G-invariant smooth fan in which no two rays of one G-orbit span a cone, and that has the rays of the fixed curves.

Starting from the rays of `act`, two things are done. First, with `property_E = true`, for every curve fixed
pointwise by an element of the group (an affine map whose linear part is a reflection) with direction `v`, the rays
`v` and `-v` are inserted by repeated star subdivision of the cone that contains them in its interior (the
Hirzebruch-Jung procedure). This is property (E) of Kresch-Tschinkel in dimension two: the closure of the curve then
meets the toric boundary transversally at points of the open orbits. The set of rays that this adds is the set of
nodes of the Stern-Brocot tree needed to reach the requested rays, so it does not depend on the order of the insertions and
the resulting fan is invariant under the group. Second, as long as two adjacent rays belong to one orbit of the linear
parts of the group, the cones of that orbit are subdivided by adding the sum of the two rays (blowup of the torus
fixed point). The result is a smooth complete fan, invariant under the group, that makes the action on the toric
surface be in standard form with respect to the boundary (see the conventions in `src/toric.jl`). For the projective
plane with an action that permutes the coordinate lines this gives the degree 6 del Pezzo surface. Without
reflections `property_E` changes nothing.

# Examples

```jldoctest
a = AffineTorusMap([1 0; 0 1], [1//8, 0])
c = AffineTorusMap([0 -1; 1 -1], [0, 0])
act = ToricAction([a, c], toric_fan_P2())
println(length(equivariant_refinement(act)))

# output

6
```
"""
function equivariant_refinement(act::ToricAction; property_E::Bool = true)
    nus = _linear_parts(act)
    rays = copy(act.rays)
    if property_E
        for v in sort!(collect(_layer_directions(act)))
            rays = _insert_ray(rays, v)
        end
        rayset = Set(rays)
        for nu in nus, r in rays
            Int.(nu * r) in rayset || error("internal error: the fan after inserting the rays of the fixed curves is not invariant")
        end
    end
    for _ in 1:25
        orb = Dict{Vector{Int},Set{Vector{Int}}}(r => _ray_orbit(r, nus) for r in rays)
        out = Vector{Int}[]
        m = length(rays)
        for i in 1:m
            r, s = rays[i], rays[mod1(i + 1, m)]
            push!(out, r)
            if orb[r] == orb[s]
                push!(out, r .+ s)
            end
        end
        length(out) == m && return rays
        rays = out
    end
    error("the refinement did not stabilize")
end

# the directions v and -v of the fixed curves of the elements of the group, as primitive vectors
function _layer_directions(act::ToricAction)
    dirs = Set{Vector{Int}}()
    for (g, f) in act.images
        f.nu == _id2() && continue
        kind = fixed_set(f)
        kind[1] == :layers || continue
        for l in kind[2]
            v = [-l.m[2], l.m[1]]
            push!(dirs, v); push!(dirs, -v)
        end
    end
    return dirs
end

# insert the primitive vector v as a ray of a smooth complete fan, subdividing the cone that contains it in its interior
function _insert_ray(rays, v)
    v in rays && return rays
    m = length(rays)
    for i in 1:m
        r, s = rays[i], rays[mod1(i + 1, m)]
        # v = a r + b s with det(r, s) = 1
        a = v[1] * s[2] - v[2] * s[1]
        b = r[1] * v[2] - r[2] * v[1]
        if a > 0 && b > 0
            new = copy(rays)
            insert!(new, i + 1, r .+ s)
            return _insert_ray(new, v)
        end
    end
    error("the vector $v is not in the interior of a cone of the fan")
end

# ---------------------------------------------------------------------------

_orbits_of_cones(rays, nus) = begin
    m = length(rays)
    cones = [(rays[i], rays[mod1(i + 1, m)]) for i in 1:m]
    key(c) = Set([c[1], c[2]])
    seen = Set{Set{Vector{Int}}}()
    reps = Tuple{Vector{Int},Vector{Int}}[]
    for c in cones
        key(c) in seen && continue
        push!(reps, c)
        for nu in nus
            push!(seen, Set([Int.(nu * c[1]), Int.(nu * c[2])]))
        end
        push!(seen, key(c))
    end
    reps
end

function _orbits_of_rays(rays, nus)
    seen = Set{Vector{Int}}()
    reps = Vector{Int}[]
    for r in rays
        r in seen && continue
        push!(reps, r)
        union!(seen, _ray_orbit(r, nus))
    end
    return reps
end

"""
    toric_class(act::ToricAction; refine = true, points = :auto, extra_points = []) -> BCClass

The class of the action on the toric surface, as a formal sum of symbols in BC_2(G).

The class is the sum, over the G-orbits of strata of a G-invariant model in standard form, of the symbols `(H, Y, beta)`:
for a ray the pointwise stabilizer `H` of the divisor (translations along the ray) with `Y` its stabilizer in `G` and the
tautological weight, for a two dimensional cone the group `A` of translations with the weights given by the coordinates of the
translation in the basis of the cone. With `refine = true` the fan is first subdivided by `equivariant_refinement`, with
`refine = false` the fan of `act` must already have the properties that no two rays of one orbit span a cone and that the
directions of the fixed curves are rays. Evaluate with `bc_image`. The generic symbol of the class (trivial stabilizer)
is not part of BC_n(G) and is omitted.

When some element of the group has a reflection as linear part, the closures of its fixed curves are part of the divisor.
Their symbols `(<h>, Stab(C), 1)` are added, together with the symbols of the blowup of each special point (interior fixed points of the
elements without fixed direction, intersections of fixed curves, and the points of the boundary where a curve meets it or that are fixed by an
inversion of the divisor): the exceptional curve with the scalar elements of the stabilizer as generic stabilizer, and the points of
that curve whose stabilizer is larger. These are computed from the linear action of the stabilizer on the tangent plane. The class
agrees, in BC_2(G), with the class printed by Kresch and Tschinkel for C_2 x S_3 acting on the del Pezzo surface of degree 6, and
it does not depend on additional blowup centers (`extra_points`, rational points of the torus) or on the fan.

`points = :auto` computes these symbols exactly when the group has reflections. With `points = true` they are computed
in any case (without reflections their total is zero in BC_2(G)), with `points = false` the class of the boundary only is returned and a group with
reflections raises `ArgumentError`. `extra_points` is a list of rational points `u` of the torus, with `exp(2 pi i u)` the point, to be blown up in
addition, which must not change the image.

# Examples

```jldoctest
a = AffineTorusMap([1 0; 0 1], [1//8, 0])
b = AffineTorusMap([1 0; 0 1], [0, 7//8])
c = AffineTorusMap([0 -1; 1 -1], [0, 0])
act = ToricAction([a, b, c], toric_fan_P2())
x = bc_image(toric_class(act))
println(is_zero(x))

# output

false
```
"""
function toric_class(act::ToricAction; refine::Bool = true, points = :auto, extra_points = Vector{Vector{Rational{Int}}}())
    nus = _linear_parts(act)
    has_reflections = any(nu -> nu != _id2() && _det2(nu - _id2()) == 0, nus)
    points in (:auto, true, false) || throw(ArgumentError("points must be :auto, true or false"))
    reflections = points === :auto ? has_reflections : points
    if has_reflections && !reflections
        throw(ArgumentError("the group has reflections (fixed curves): use points = :auto or true"))
    end
    rays = refine ? equivariant_refinement(act) : act.rays
    if !refine
        for i in eachindex(rays)
            r, s = rays[i], rays[mod1(i + 1, length(rays))]
            _ray_orbit(r, nus) == _ray_orbit(s, nus) && throw(ArgumentError(
                "the rays $r and $s of one orbit span a cone: use refine = true"))
        end
        if has_reflections
            rs = Set(rays)
            all(v -> v in rs, _layer_directions(act)) || throw(ArgumentError(
                "a fixed curve has a direction that is not a ray (property (E)): use refine = true"))
        end
    end
    G = act.G
    cls = BCClass(G, 2)
    elems = collect(keys(act.images))
    Aelems = [g for g in elems if act.images[g].nu == _id2()]
    if length(Aelems) == 1
        reflections && _reflection_symbols!(cls, act, rays, extra_points)
        return cls
    end
    A, _ = sub(G, Aelems)
    # divisors
    for rho in _orbits_of_rays(rays, nus)
        p, q = rho
        gg, u, v = gcdx(p, q)
        if gg < 0
            u, v = -u, -v
        end
        pp, qq = -v, u                      # rho' = (pp, qq) with det(rho, rho') = p qq - q pp = 1
        @assert p * qq - q * pp == 1
        Hr = [a for a in Aelems if isinteger(q * act.images[a].t[1] - p * act.images[a].t[2])]
        length(Hr) == 1 && continue
        a0 = Hr[argmax([Int(order(a)) for a in Hr])]
        k = Int(order(a0))
        k == length(Hr) || error("the pointwise stabilizer of a divisor is not cyclic")
        t = act.images[a0].t
        mu = t[1] * qq - t[2] * pp
        c = mu * k
        denominator(c) == 1 || error("weight is not an integer")
        stab = [g for g in elems if Int.(act.images[g].nu * rho) == rho]
        S, _ = sub(G, stab)
        push!(cls, BCSymbol(G, [a0], gens(S), [[mod(Int(numerator(c)), k)]]))
    end
    # fixed points of the torus
    gA = GAP.Globals.IndependentGeneratorsOfAbelianGroup(GAP.GapObj(A))
    agens = [Oscar.group_element(G, gA[i]) for i in 1:length(gA)]
    ords = [Int(order(a)) for a in agens]
    for (r1, r2) in _orbits_of_cones(rays, nus)
        d = r1[1] * r2[2] - r1[2] * r2[1]
        d == 1 || ((r1, r2) = (r2, r1))     # orient the pair so that det(r1, r2) = 1
        b1 = Vector{Int}(); b2 = Vector{Int}()
        for (a, o) in zip(agens, ords)
            t = act.images[a].t
            l1 = r2[2] * t[1] - r2[1] * t[2]
            l2 = -r1[2] * t[1] + r1[1] * t[2]
            c1, c2 = l1 * o, l2 * o
            (denominator(c1) == 1 && denominator(c2) == 1) || error("weight is not an integer")
            push!(b1, mod(Int(numerator(c1)), o)); push!(b2, mod(Int(numerator(c2)), o))
        end
        (all(==(0), b1) || all(==(0), b2)) && continue
        push!(cls, BCSymbol(G, agens, [], [b1, b2]))
    end
    reflections && _reflection_symbols!(cls, act, rays, extra_points)
    return cls
end
