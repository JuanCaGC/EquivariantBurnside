# ---------------------------------------------------------------------------
# Toric surfaces with reflections: the class in BC_2(G) from the standard form model.
#
# Model. After `equivariant_refinement` (rays of the fixed curves, no two rays of an orbit adjacent) the divisor D is the
# toric boundary plus the closures of the fixed curves of the reflections. D has simple normal crossings except at the
# special points, where several components meet or the stabilizer is not generic. Blowing up every special point p once gives
# the standard form model:
#   R1 After the blowup of p the exceptional curve E = P(T_p) has the group S_p acting through its linear action R on the
#      tangent plane T_p. The elements acting trivially on E are the scalars Z_p = {g : R_g scalar}. The points of E with a
#      stabilizer larger than Z_p are the lines l that are eigenlines of some nonscalar R_g. By Maschke the stabilizer S_l
#      of a line is abelian and acts on T_p = l + (T_p / l) by two characters. The weights at the point q_l of E are the
#      character chi_l of S_l on l (normal to E) and the character of S_l on T_p / l divided by chi_l (tangent to E).
#   R2 Symbols (H, Y~, beta) of the final model that come from p: for E when Z_p is nontrivial, (Z_p, S_p, scalar
#      character), and for each S_p-orbit of special lines l the point symbol (S_l, S_l, (chi_l, chi_{T/l} chi_l^-1)),
#      omitted when one of the two characters is trivial on S_l (the point then lies on a fixed curve).
#   R3 The strict transforms of the fixed curves and of the boundary divisors keep their symbols.
#  The symbols of the remaining strata of the model are those of `toric_class`: boundary divisors, torus fixed points
#  of the boundary, and the generic points of the fixed curves, (<h>, Stab(C), 1) for the reflection h fixing C pointwise.
#
# Coordinates for the tangent action.
#  I1 Interior point u: g in S_p acts on T_p = N (x) C by the integer matrix nu_g.
#  B1 Point of the open orbit D_rho of the ray rho, with coordinate w = det(rho, u) mod 1. Take rho' with det(rho, rho') = 1
#     and write nu rho = rho, nu rho' = k rho + s rho', t = t_a rho + t_b rho'. In the coordinates z1 = e^(2 pi i a) (vanishing on D_rho)
#     and z2 = e^(2 pi i b) of u = a rho + b rho' the map is z1 -> e^(2 pi i t_a) z1 z2^k, z2 -> e^(2 pi i t_b) z2^s. At a point of D_rho
#     fixed by g the differential is diagonal, diag(exp(2 pi i (t_a + k w)), s), in the basis (normal, tangent to D_rho).
# All eigenvalues are roots of unity and are computed with floating point complex numbers and rounded to integer exponents with
# a check, never used as exact data otherwise.
# ---------------------------------------------------------------------------

const _TOLC = 1e-8

# subgroup generated by a list of elements, whatever the element type of the list is
_subgroup(G, els) = sub(G, [g for g in els])
_cisq(x) = cis(2pi * Float64(x))

struct LocalPoint
    kind::Symbol                          # :interior or :boundary
    stab::Vector{Any}                     # the stabilizer S_p, elements of G
    mats::Dict{Any,Matrix{ComplexF64}}    # tangent action of each element
end

_mmul(A, v) = [A[1, 1] * v[1] + A[1, 2] * v[2], A[2, 1] * v[1] + A[2, 2] * v[2]]
_mdet(A) = A[1, 1] * A[2, 2] - A[1, 2] * A[2, 1]
_isscalar(A) = abs(A[1, 2]) < _TOLC && abs(A[2, 1]) < _TOLC && abs(A[1, 1] - A[2, 2]) < _TOLC
_sameline(v, w) = abs(v[1] * w[2] - v[2] * w[1]) < _TOLC * max(1.0, abs(v[1]) + abs(v[2])) * max(1.0, abs(w[1]) + abs(w[2]))

function _linekey(v)
    if abs(v[1]) > _TOLC
        z = v[2] / v[1]
        return (round(real(z); digits = 6), round(imag(z); digits = 6))
    end
    return (Inf, Inf)
end

# the eigenlines of a nonscalar 2 by 2 matrix, as vectors
function _eigenlines(A)
    tr = A[1, 1] + A[2, 2]
    d = _mdet(A)
    disc = sqrt(tr^2 - 4d)
    lines = Vector{ComplexF64}[]
    for lam in ((tr + disc) / 2, (tr - disc) / 2)
        v = if abs(A[1, 2]) > _TOLC
            ComplexF64[A[1, 2], lam - A[1, 1]]
        elseif abs(A[2, 1]) > _TOLC
            ComplexF64[lam - A[2, 2], A[2, 1]]
        elseif abs(lam - A[1, 1]) < _TOLC
            ComplexF64[1, 0]
        else
            ComplexF64[0, 1]
        end
        push!(lines, v)
    end
    return lines
end

# integer c in Z/o with chi = exp(2 pi i c / o), checked
function _expo(chi, o)
    x = angle(chi) / (2pi) * o
    c = round(Int, x)
    abs(x - c) < 1e-6 || error("the weight $chi is not a root of unity of order dividing $o")
    abs(abs(chi) - 1) < 1e-6 || error("the weight $chi is not of modulus one")
    return mod(c, o)
end

# the symbols that the blowup of the point contributes, as (hgens, ygens, betas) with elements of G
function _blowup_symbols(G, lp::LocalPoint)
    S = lp.stab
    out = Tuple{Vector{Any},Vector{Any},Vector{Vector{Int}}}[]
    Sgrp, _ = _subgroup(G, S)
    # (R1) the exceptional curve: the scalars
    Z = [g for g in S if _isscalar(lp.mats[g])]
    if length(Z) > 1
        z = Z[argmax([Int(order(g)) for g in Z])]
        o = Int(order(z))
        o == length(Z) || error("the scalar subgroup is not cyclic")
        c = _expo(lp.mats[z][1, 1], o)
        c == 0 && error("a scalar generator with trivial weight")
        push!(out, (Any[z], Any[gg for gg in gens(Sgrp)], [[c]]))
    end
    # special lines
    lines = Vector{ComplexF64}[]
    seen = Set{Tuple{Float64,Float64}}()
    for g in S
        _isscalar(lp.mats[g]) && continue
        for v in _eigenlines(lp.mats[g])
            k = _linekey(v)
            k in seen && continue
            push!(seen, k); push!(lines, v)
        end
    end
    # orbits of the lines under S
    done = Set{Tuple{Float64,Float64}}()
    for v in lines
        k = _linekey(v)
        k in done && continue
        for g in S
            push!(done, _linekey(_mmul(lp.mats[g], v)))
        end
        Sl = [g for g in S if _sameline(_mmul(lp.mats[g], v), v)]
        Slgrp, _ = _subgroup(G, Sl)
        is_abelian(Slgrp) || error("the stabilizer of a line is not abelian")
        gA = GAP.Globals.IndependentGeneratorsOfAbelianGroup(GAP.GapObj(Slgrp))
        hg = Any[Oscar.group_element(G, gA[i]) for i in 1:length(gA)]
        ords = [Int(order(h)) for h in hg]
        kk = abs(v[1]) > abs(v[2]) ? 1 : 2
        chi1 = [ (_mmul(lp.mats[h], v)[kk] / v[kk]) for h in hg]
        chi2 = [ (_mdet(lp.mats[h]) / (_mmul(lp.mats[h], v)[kk] / v[kk])^2) for h in hg]
        b1 = [_expo(x, o) for (x, o) in zip(chi1, ords)]
        b2 = [_expo(x, o) for (x, o) in zip(chi2, ords)]
        (all(==(0), b1) || all(==(0), b2)) && continue
        push!(out, (hg, Any[], [b1, b2]))
    end
    return out
end

