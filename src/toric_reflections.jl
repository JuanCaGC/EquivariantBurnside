# local data of the special points

# the layer {m . u = c} moved by the affine map f: {(m nu^-1) . u = c + (m nu^-1) . t}
function _move_layer(l::FixedLayer, f::AffineTorusMap)
    d = _det2(f.nu)
    ninv = d * [f.nu[2, 2] -f.nu[1, 2]; -f.nu[2, 1] f.nu[1, 1]]
    mm = vec(l.m' * ninv)
    return FixedLayer(mm, l.c + (mm[1] * f.t[1] + mm[2] * f.t[2]))
end

function _interior_points(act::ToricAction, extra)
    cand = Vector{Rational{Int}}[p.u for p in special_points(act)]
    for u in extra
        push!(cand, Rational{Int}[_mod1(Rational{Int}(x)) for x in u])
    end
    out = LocalPoint[]
    done = Set{Vector{Rational{Int}}}()
    for u in sort!(unique(cand))
        u in done && continue
        for (g, f) in act.images
            push!(done, _apply(f, u))
        end
        stab = [g for (g, f) in act.images if _fixes(f, u)]
        length(stab) > 1 || continue
        mats = Dict{Any,Matrix{ComplexF64}}(g => ComplexF64.(act.images[g].nu) for g in stab)
        push!(out, LocalPoint(:interior, Any[g for g in stab], mats))
    end
    return out
end

# special points of the open orbits of the boundary, with the local data, one for each orbit of the group
function _boundary_points(act::ToricAction, rays, layers)
    elems = collect(keys(act.images))
    cand = Set{Tuple{Vector{Int},Rational{Int}}}()
    for rho in rays
        for g in elems
            f = act.images[g]
            Int.(f.nu * rho) == rho || continue
            _det2(f.nu) == -1 || continue
            c = _mod1(Rational{Int}(rho[1] * f.t[2] - rho[2] * f.t[1]))
            for j in 0:1
                push!(cand, (rho, _mod1((c + j) // 2)))
            end
        end
        for l in layers
            v = [-l.m[2], l.m[1]]
            (v == rho || v == -rho) || continue
            u0 = l.m[1] != 0 ? Rational{Int}[l.c // l.m[1], 0] : Rational{Int}[0, l.c // l.m[2]]
            push!(cand, (rho, _mod1(Rational{Int}(rho[1] * u0[2] - rho[2] * u0[1]))))
        end
    end
    out = LocalPoint[]
    done = Set{Tuple{Vector{Int},Rational{Int}}}()
    for (rho, w) in sort!(collect(cand))
        (rho, w) in done && continue
        # the orbit of the point under the group
        for g in elems
            f = act.images[g]
            nr = Int.(f.nu * rho)
            w2 = _mod1(Rational{Int}(_det2(f.nu) * w + (nr[1] * f.t[2] - nr[2] * f.t[1])))
            push!(done, (nr, w2))
        end
        p, q = rho
        gg, u, v = gcdx(p, q)
        gg < 0 && ((u, v) = (-u, -v))
        pp, qq = -v, u
        stab = Any[]
        mats = Dict{Any,Matrix{ComplexF64}}()
        for g in elems
            f = act.images[g]
            Int.(f.nu * rho) == rho || continue
            x, y = f.nu * [pp, qq]
            s = p * y - q * x
            k = x * qq - y * pp
            ta = f.t[1] * qq - f.t[2] * pp
            tb = p * f.t[2] - q * f.t[1]
            isinteger(s * w + tb - w) || continue
            push!(stab, g)
            mats[g] = ComplexF64[_cisq(ta + k * w) 0; 0 s]
        end
        # the pointwise stabilizer of the divisor: linear part the identity and translation along rho
        Hrho = [g for g in stab if act.images[g].nu == _id2() && isinteger(rho[1] * act.images[g].t[2] - rho[2] * act.images[g].t[1])]
        length(stab) > length(Hrho) || continue
        push!(out, LocalPoint(:boundary, stab, mats))
    end
    return out
end

# the symbols of the fixed curves and of the blowups of the special points
function _reflection_symbols!(cls::BCClass, act::ToricAction, rays, extra = Vector{Vector{Rational{Int}}}())
    G = act.G
    fc = fixed_curves(act)
    layers = [c.layer for c in fc]
    seen = Set{FixedLayer}()
    for c in fc
        c.layer in seen && continue
        union!(seen, Set(_move_layer(c.layer, f) for (g, f) in act.images))
        h = first(g for g in c.H if act.images[g].nu != _id2())
        order(h) == 2 || error("the generic stabilizer of a fixed curve has order $(order(h))")
        stab = Any[g for (g, f) in act.images if _move_layer(c.layer, f) == c.layer]
        S, _ = _subgroup(G, stab)
        push!(cls, BCSymbol(G, [h], Any[x for x in gens(S)], [[1]]))
    end
    for lp in vcat(_interior_points(act, extra), _boundary_points(act, rays, layers))
        for (hg, yg, bs) in _blowup_symbols(G, lp)
            push!(cls, BCSymbol(G, hg, yg, bs))
        end
    end
    return cls
end
