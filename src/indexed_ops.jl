# Operations omega, restriction and product on indexed classes (Phase 4.3).
#
# Conventions, as in `indexed.jl`: a symbol is (H in A, Y~, beta, gamma) in subgroup notation, with A the abelian group that
# carries the characters and Y~ inside the centralizer of A. Conjugation is x^g = g^-1 x g.

"""
    indexed_omega(cls, J)

The homomorphism `omega_{I,J}` of Kresch-Tschinkel (KT-struct Section 4, KT-repr Section 4) for `J` a subset of the index set `I`.

For a symbol `(H in A, Y~, beta, gamma)` let `A'` be the intersection of the kernels in `A` of the characters `gamma_i` for `i` in
`I` minus `J`. The image is `(H cap A' in A', Y~, beta|A', gamma_J|A')` with the transcendence degree raised by `|I minus J|`.
The subgroup `Y~` is not changed (the centralizer is that of the ORIGINAL `A`) and the elements of `A` outside `A'` now act on
the new variables by the values of the removed characters. The image is zero when some restricted character of `beta` vanishes
on `A'`. A removed character that is zero is allowed, unlike for `psi`. The dimension `n` is unchanged.

Returns an `IndexedClass` with the index set `J`. Throws `ArgumentError` when `J` is not a subset of `I`.
"""
function indexed_omega(cls::IndexedClass, J)
    Jl = sort!(Int[j for j in J])
    all(j in cls.I for j in Jl) || throw(ArgumentError("J must be a subset of the index set $(cls.I)"))
    length(unique(Jl)) == length(Jl) || throw(ArgumentError("J has repeated indices"))
    out = IndexedClass(cls.G, cls.n, Jl, cls.elems, cls.idx, Dict{Any,Tuple{Int,IndexedSymbol}}())
    rem = [i for i in cls.I if !(i in Jl)]
    for (_, (coef, s)) in cls.terms
        A2 = Any[a for a in s.A if all(iszero(s.gamma[i][a]) for i in rem)]
        rs(c) = Dict{Any,Rational{Int}}(a => c[a] for a in A2)
        beta2 = Dict{Any,Rational{Int}}[rs(c) for c in s.beta]
        any(all(iszero(v) for v in values(c)) for c in beta2) && continue
        A2set = Set(A2)
        H2 = Any[h for h in s.H if h in A2set]
        gm = Dict{Int,Dict{Any,Rational{Int}}}(j => rs(s.gamma[j]) for j in Jl)
        isempty(s.F) || throw(ArgumentError("omega adds a torus to the field and is not supported on symbols that carry a field datum"))
        push!(out, coef, IndexedSymbol(s.G, H2, A2, s.Y, s.d + length(rem), beta2, gm))
    end
    return out
end

"""
    indexed_restrict(cls, Lgens)

The restriction of `cls` from `G` to the subgroup `L` generated by `Lgens` (KT-struct Theorem 7.2 in subgroup notation).

Returns `(cls_L, L, emb)` with `cls_L` an `IndexedClass` of the group `L`, and `emb` the embedding of `L` in `G`. Every symbol
`(H in A, Y~, beta, gamma)` of `cls` goes to the sum, over a set of representatives `k` of the double cosets `L k Y~` of `G`
(with `g = k^-1`), of the symbols `(H^g cap L in A^g cap L, Y~^g cap L, beta^g|, gamma^g|)` in which the characters are
transported by conjugation and restricted. A term is dropped when some restricted character of `beta` vanishes. The
transcendence degree and the index set do not change. Conjugating the symbol by an element of `Y~` or by `L` gives the same term
up to conjugation in `L`.

# Examples

```jldoctest
S4 = symmetric_group(4)
D4, _ = sub(S4, [perm(S4, [2, 3, 4, 1]), perm(S4, [3, 2, 1, 4])])
r = D4(perm(S4, [2, 3, 4, 1]))
chi = indexed_character(D4, [r], [1])
cls = IndexedClass(D4, 1, Int[])
push!(cls, IndexedSymbol(D4, [], [r], [r], 0, [chi], Dict{Int,Dict{Any,Rational{Int}}}()))
out, L, emb = indexed_restrict(cls, [r])
println(order(L), " ", length(out))

# output

4 2
```
"""
function indexed_restrict(cls::IndexedClass, Lgens)
    G = cls.G
    L, emb = sub(G, elem_type(G)[g for g in Lgens])
    Lel = Any[x for x in L]
    Limg = Dict{Any,Any}(emb(l) => l for l in Lel)
    out = IndexedClass(L, cls.n, cls.I)
    for (_, (coef, s)) in cls.terms
        Ysub, _ = sub(G, elem_type(G)[y for y in s.Y])
        for D in double_cosets(G, L, Ysub)
            g = inv(representative(D))
            conj(x) = x^g
            keep(x) = haskey(Limg, conj(x))
            A2 = Any[conj(a) for a in s.A if keep(a)]
            rs(c) = Dict{Any,Rational{Int}}(Limg[conj(a)] => v for (a, v) in c if keep(a))
            beta2 = Dict{Any,Rational{Int}}[rs(c) for c in s.beta]
            any(all(iszero(v) for v in values(c)) for c in beta2) && continue
            H2 = Any[Limg[conj(h)] for h in s.H if keep(h)]
            Y2 = Any[Limg[conj(y)] for y in s.Y if keep(y)]
            A2L = Any[Limg[a] for a in A2]
            gm = Dict{Int,Dict{Any,Rational{Int}}}(i => rs(c) for (i, c) in s.gamma)
            F2 = _move_field(s.F, y -> Limg[conj(y)], keep)
            push!(out, coef, IndexedSymbol(L, H2, A2L, Y2, s.d, beta2, gm, F2, Val(:raw)))
        end
    end
    return out, L, emb
end

"""
    indexed_product(a, b)

The product of KT-struct Section 6, formula (6.1), of two indexed classes, in the direct product of their groups.

`a` is a class of a group `G1` in dimension `n1` with index set `I1` and `b` a class of `G2` in dimension `n2` with index set
`I2`, and the two index sets must be disjoint. The symbol `(H1 in A1, Y1~, beta1, gamma1)` times `(H2 in A2, Y2~, beta2,
gamma2)` is `(H1 x H2 in A1 x A2, Y1~ x Y2~, beta1 followed by beta2, gamma1 and gamma2 together)`, with the transcendence
degrees added, where every character is extended by zero on the other factor. The result is a class of `G1 x G2` of dimension
`n1 + n2` with index set the union. Returns `(cls, P, emb1, emb2)` with `P` the direct product group and its two embeddings.
"""
function indexed_product(a::IndexedClass, b::IndexedClass)
    isempty(intersect(a.I, b.I)) || throw(ArgumentError("the index sets of the two classes must be disjoint"))
    P = direct_product(a.G, b.G)
    e1 = embedding(P, 1)
    e2 = embedding(P, 2)
    out = IndexedClass(P, a.n + b.n, sort!(vcat(a.I, b.I)))
    ext1(c, A2) = Dict{Any,Rational{Int}}(e1(x) * e2(y) => v for (x, v) in c for y in A2)
    ext2(c, A1) = Dict{Any,Rational{Int}}(e1(x) * e2(y) => v for (y, v) in c for x in A1)
    for (_, (c1, s1)) in a.terms, (_, (c2, s2)) in b.terms
        prod(X, Y) = Any[e1(x) * e2(y) for x in X for y in Y]
        beta = vcat(Dict{Any,Rational{Int}}[ext1(c, s2.A) for c in s1.beta], Dict{Any,Rational{Int}}[ext2(c, s1.A) for c in s2.beta])
        gm = Dict{Int,Dict{Any,Rational{Int}}}()
        for (i, c) in s1.gamma
            gm[i] = ext1(c, s2.A)
        end
        for (i, c) in s2.gamma
            gm[i] = ext2(c, s1.A)
        end
        F = vcat(Any[FieldFactor(x.dim, Dict{Any,Vector{Rational{Int}}}(e1(y1) * e2(y2) => v for (y1, v) in x.inv for y2 in s2.Y),
                                 Dict{Any,Any}(e1(y1) * e2(y2) => v for (y1, v) in x.tr for y2 in s2.Y)) for x in s1.F],
                 Any[FieldFactor(x.dim, Dict{Any,Vector{Rational{Int}}}(e1(y1) * e2(y2) => v for (y2, v) in x.inv for y1 in s1.Y),
                                 Dict{Any,Any}(e1(y1) * e2(y2) => v for (y2, v) in x.tr for y1 in s1.Y)) for x in s2.F])
        push!(out, c1 * c2, IndexedSymbol(P, prod(s1.H, s2.H), prod(s1.A, s2.A), prod(s1.Y, s2.Y), s1.d + s2.d, beta, gm, F, Val(:raw)))
    end
    return out, P, e1, e2
end
